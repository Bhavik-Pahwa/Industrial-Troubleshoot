import { test, expect } from '@playwright/test';

const api = 'http://127.0.0.1:8000/api/v1';

test('live browser ingestion reaches AI, displays assessment, and supports incident lifecycle', async ({ page, request }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  const health = await request.get(`${api}/system/status`);
  expect(await health.json()).toMatchObject({ status: 'healthy', detector: 'ready', llm: 'ready' });

  await page.goto('/ingest');
  await expect(page.getByText('Backend API Live', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Pump pump-01 Normal Batch (2 readings)' }).click();
  const normalResponse = page.waitForResponse(r => r.url() === `${api}/telemetry/ingest` && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Submit Batch to API' }).click();
  expect(await (await normalResponse).json()).toMatchObject({ accepted: 2, rejected: 0 });
  await expect(page.getByText('Per-Reading Results (2 items)')).toBeVisible();

  await page.getByRole('button', { name: 'Motor motor-01 Thermal Excursion (2 readings)' }).click();
  const anomalyResponse = page.waitForResponse(r => r.url() === `${api}/telemetry/ingest` && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Submit Batch to API' }).click();
  expect(await (await anomalyResponse).json()).toMatchObject({ accepted: 2, rejected: 0 });
  const incidents = await (await request.get(`${api}/incidents?asset_id=motor-01&status=open`)).json();
  const incident = incidents.items.find((item: any) => item.anomaly_category === 'high_temperature');
  expect(incident.latest_evidence).toMatchObject({ detector: 'ai_service', analysis_source: 'ollama', model: 'qwen2.5:3b' });
  expect(incident.latest_evidence.explanation.length).toBeGreaterThan(20);

  await page.goto(`/incidents/${incident.id}`);
  await expect(page.getByRole('heading', { name: 'AI Assessment' })).toBeVisible();
  await expect(page.getByText('Generated by qwen2.5:3b')).toBeVisible();
  await page.screenshot({ path: '../.runtime/ai-assessment.png', fullPage: true });
  await page.getByRole('button', { name: /acknowledge/i }).click();
  await expect.poll(async () => (await (await request.get(`${api}/incidents/${incident.id}`)).json()).status).toBe('acknowledged');
  await page.getByRole('button', { name: /resolve incident/i }).click();
  await page.getByRole('textbox').fill('Resolved during automated full-stack integration verification.');
  await page.getByRole('button', { name: /confirm resolution/i }).click();
  await expect.poll(async () => (await (await request.get(`${api}/incidents/${incident.id}`)).json()).status).toBe('resolved');

  await page.goto('/ingest');
  await expect(page.getByText('Backend API Live', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Batch with Invalid Reading (Per-Item Rejection)' }).click();
  const mixedResponse = page.waitForResponse(r => r.url() === `${api}/telemetry/ingest` && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Submit Batch to API' }).click();
  expect(await (await mixedResponse).json()).toMatchObject({ accepted: 1, rejected: 1 });

  await page.goto('/assets/pump-01');
  await expect(page.getByText('Cooling Water Pump', { exact: true })).toBeVisible();
  await page.goto('/dashboard');
  await expect(page.getByText('Backend API Live', { exact: true })).toBeVisible();
  await page.screenshot({ path: '../.runtime/dashboard.png', fullPage: true });
  expect(errors).toEqual([]);
});
